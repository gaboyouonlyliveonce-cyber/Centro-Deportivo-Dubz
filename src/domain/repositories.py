from datetime import date
from typing import Any, Dict, List, Protocol
from .entities import Cliente, Entrenamiento, HistorialMarca


class ClienteRepository(Protocol):
    def crear_cliente(self, cliente: Cliente) -> int: ...
    def agregar_marca(self, id_cliente: int, marca: HistorialMarca) -> int: ...
    def obtener_marcas_vigentes(self) -> List[Dict[str, Any]]: ...


class MembresiaRepository(Protocol):
    def asignar_membresia(self, id_cliente: int, id_tipo_membresia: int, fecha_inicio: date) -> int: ...
    def listar_recordatorios_pendientes(self) -> List[Dict[str, Any]]: ...
    def marcar_recordatorio_enviado(self, id_membresia: int) -> None: ...


class RecepcionRepository(Protocol):
    def anotar_consumo_pendiente(self, id_cliente: int, id_producto: int, cantidad: int) -> int: ...
    def consultar_adeudos_clientes(self) -> List[Dict[str, Any]]: ...
    def liquidar_adeudo_cliente(self, id_cliente: int) -> float: ...


class EntrenamientoRepository(Protocol):
    def guardar_entrenamiento_completo(self, entrenamiento: Entrenamiento) -> int: ...
    def obtener_entrenamiento_por_fecha(self, fecha_sesion: date) -> List[Dict[str, Any]]: ...